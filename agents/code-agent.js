// الدالة الرئيسية
// ════════════════════════════════════════════
export async function run(idea, story, levels, art, template) {
  logger.info('[INFO] Code Agent started', { id: idea.id, type: idea.type });

  const isGodot = idea.type === 'godot';

  if (!isGodot) {
    logger.info('[INFO] Non-Godot project — skipping Godot code generation');
    return { slug: idea.id, files: [], engine: 'phaser' };
  }

  const soul = soulContext('codeAgent');
  const slug = idea.id;
  const files = [];

  // 1. export_presets.cfg — ثابت لا يحتاج Gemini
  writeProjectFile(slug, 'export_presets.cfg', generateExportPresets());
  files.push('export_presets.cfg');

  // 2. project.godot — ثابت لا يحتاج Gemini
  writeProjectFile(slug, 'project.godot', buildProjectGodot(idea));
  files.push('project.godot');

  // 3. ملفات GDScript
  logger.info('[INFO] Generating GDScript files...');
  try {
    const worldNames  = levels?.worlds?.map(w => w.name?.en).join(', ') || '';
    const heroName    = story?.mainCharacter?.name || 'Hero';
    const movementTip = loadRecipes('movement');
    const shaderTip   = loadRecipes('shaders');

    const scripts = await askGemini(`
${soul}

اكتب GDScript كامل لـ Godot 4.6.2.
اسم اللعبة: "${idea.name?.en}"
البطل: ${heroName}
العوالم: ${worldNames}

${movementTip ? `وصفات الحركة المتاحة:\n${movementTip}` : ''}
${shaderTip   ? `وصفات البصريات المتاحة:\n${shaderTip}`  : ''}

القواعد الصارمة:
- tabs للـ indentation فقط — ليس spaces
- preload() للمراجع الثابتة
- add_to_group("player") في _ready() في player.gd
- add_to_group("enemy") في _ready() في enemy.gd
- is_inside_tree() قبل queue_free() بعد await
- process_mode = ALWAYS في main_scene.gd
- دعم InputEventScreenTouch مع InputEventMouseButton
- gravity_scale = 0.0 في bullet
- fire action يستخدم pressed:true

أنتج JSON فقط — مفاتيحه أسماء الملفات وقيمه الكود:
{
  "main_scene.gd": "...",
  "player.gd":     "...",
  "enemy.gd":      "...",
  "weapon.gd":     "...",
  "bullet.gd":     "..."
}`, 0.7, { topP: 0.9, maxOutputTokens: 8192 });

    const required = ['main_scene.gd', 'player.gd', 'enemy.gd', 'weapon.gd', 'bullet.gd'];
    for (const f of required) {
      if (!scripts[f]) {
        logger.warn(`[WARN] Missing script: ${f} — will be skipped`);
        continue;
      }
      const fixed = applyScriptRules(f, scripts[f]);
      writeProjectFile(slug, f, fixed);
      files.push(f);
    }
  } catch (err) {
    logger.error('[ERROR] GDScript generation failed', { error: err.message });
  }

  // 4. ملفات .tscn
  logger.info('[INFO] Generating .tscn scene files...');
  try {
    const scenes = await askGemini(`
اكتب ملفات .tscn لـ Godot 4.6.2.
المشروع: "${idea.id}"
الملفات المتوفرة: main_scene.gd, player.gd, enemy.gd, weapon.gd, bullet.gd

القواعد الصارمة:
- load_steps = عدد ext_resource + عدد sub_resource بالضبط
- current = true في Camera3D
- contact_monitor = true + max_contacts_reported = 1 في bullet.tscn
- connection signal=body_entered في bullet.tscn
- collision_mask = 3 للعدو
- gravity_scale = 0.0 في bullet.tscn
- process_mode = 3 في main_scene.tscn
- جميع أسماء الملفات lowercase

أنتج JSON فقط:
{
  "main_scene.tscn": "...",
  "player.tscn":     "...",
  "enemy.tscn":      "...",
  "weapon.tscn":     "...",
  "bullet.tscn":     "..."
}`, 0.5, { maxOutputTokens: 8192 });

    for (const [filename, content] of Object.entries(scenes)) {
      if (typeof content !== 'string' || content.trim().length === 0) {
        logger.warn(`[WARN] Empty scene: ${filename} — skipping`);
        continue;
      }
      const fixed = fixLoadSteps(content);
      writeProjectFile(slug, filename, fixed);
      files.push(filename);
    }
  } catch (err) {
    logger.error('[ERROR] Scene generation failed', { error: err.message });
  }

  // 5. worlds.json للاستخدام المستقبلي
  if (levels) {
    writeProjectFile(slug, 'worlds.json', JSON.stringify(levels, null, 2));
    files.push('worlds.json');
  }

  // 6. إضافة للمنتجات
  addToProducts(idea, art, levels);

  logger.info('[OK] Code Agent finished', { slug, totalFiles: files.length });
  return { slug, files, engine: 'godot', totalFiles: files.length };
}
